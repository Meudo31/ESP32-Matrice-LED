#define POLICE_DEGRE  95
#define POLICE_EURO   96
#define POLICE_COEUR  97

// Donne le numéro de glyphe d'un caractère Unicode. Les lettres accentuées
// perdent leur accent (é devient e) : 7 lignes de haut, c'est trop petit pour les accents.
uint8_t glyphePour(uint32_t c) {
  if (c >= 0x20 && c <= 0x7E) return c - 0x20;
  switch (c) {
    case 0xB0: return POLICE_DEGRE;
    case 0x20AC: return POLICE_EURO;
    case 0x2665: case 0x2764: return POLICE_COEUR;
    case 0xE0: case 0xE2: case 0xE4: return 'a' - 0x20;
    case 0xC0: case 0xC2: case 0xC4: return 'A' - 0x20;
    case 0xE7: return 'c' - 0x20;
    case 0xC7: return 'C' - 0x20;
    case 0xE8: case 0xE9: case 0xEA: case 0xEB: return 'e' - 0x20;
    case 0xC8: case 0xC9: case 0xCA: case 0xCB: return 'E' - 0x20;
    case 0xEE: case 0xEF: return 'i' - 0x20;
    case 0xCE: case 0xCF: return 'I' - 0x20;
    case 0xF4: case 0xF6: return 'o' - 0x20;
    case 0xD4: case 0xD6: return 'O' - 0x20;
    case 0xF9: case 0xFB: case 0xFC: return 'u' - 0x20;
    case 0xD9: case 0xDB: case 0xDC: return 'U' - 0x20;
    case 0x2019: return '\'' - 0x20;   // apostrophe typographique des téléphones
  }
  return '?' - 0x20;
}

// Lit le prochain caractère d'un texte UTF-8 et avance la position
uint32_t lireUtf8(const char* texte, size_t& pos) {
  uint8_t c = texte[pos++];
  if (c < 0x80) return c;
  uint8_t suite = (c >= 0xF0) ? 3 : (c >= 0xE0) ? 2 : (c >= 0xC0) ? 1 : 0;
  uint32_t code = c & (0x3F >> suite);
  while (suite-- && (texte[pos] & 0xC0) == 0x80) code = (code << 6) | (texte[pos++] & 0x3F);
  return code;
}
